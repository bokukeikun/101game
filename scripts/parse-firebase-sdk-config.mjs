#!/usr/bin/env node
/**
 * firebase apps:sdkconfig の出力（JSON または JS）を .env.development.local 形式に変換
 */
import { readFileSync, writeFileSync } from 'node:fs'

const [inputPath, outputPath] = process.argv.slice(2)
if (!inputPath || !outputPath) {
  console.error('Usage: parse-firebase-sdk-config.mjs <sdk-config-file> <output-env-file>')
  process.exit(1)
}

const raw = readFileSync(inputPath, 'utf8').trim()

/** @type {Record<string, string>} */
let config

try {
  const parsed = JSON.parse(raw)
  config = parsed.sdkConfig ?? parsed.result?.sdkConfig ?? parsed
} catch {
  const objectMatch = raw.match(/\{[\s\S]*\}/)
  if (!objectMatch) {
    console.error('SDK config の解析に失敗しました')
    process.exit(1)
  }
  config = Function(`return ${objectMatch[0]}`)()
}

const required = [
  'apiKey',
  'authDomain',
  'projectId',
  'storageBucket',
  'messagingSenderId',
  'appId',
]

for (const key of required) {
  if (!config[key]) {
    console.error(`SDK config に ${key} がありません`)
    process.exit(1)
  }
}

const env = `# ローカル開発用（yarn dev）
# Auto-generated by scripts/setup-dev-firebase.sh

VITE_FIREBASE_API_KEY=${config.apiKey}
VITE_FIREBASE_AUTH_DOMAIN=${config.authDomain}
VITE_FIREBASE_PROJECT_ID=${config.projectId}
VITE_FIREBASE_STORAGE_BUCKET=${config.storageBucket}
VITE_FIREBASE_MESSAGING_SENDER_ID=${config.messagingSenderId}
VITE_FIREBASE_APP_ID=${config.appId}

VITE_USE_FIREBASE_EMULATOR=false
`

writeFileSync(outputPath, env)
console.log(`Wrote ${outputPath}`)
